#!/usr/bin/env python3
"""从型号卡片和原始报告生成厂商能力摘要、验证状态页；不发送请求。"""

from __future__ import annotations

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[3]
REFERENCES = ROOT / "skills/model-manual/references"
CATALOG = REFERENCES / "vendors.json"
STATUS_PAGE = ROOT / "docs/验证状态.md"
TEST_IDS = {
    "chat_completions": "chat_completions",
    "streaming": "streaming",
    "thinking": "thinking_enabled",
    "thinking_off": "thinking_disabled",
    "json_object": "json_object",
    "structured_output": "structured_output",
    "tool_calling": "tool_calling",
    "vision": "vision",
}


def report_tests(report: dict) -> dict:
    if isinstance(report.get("tests"), dict):
        return report["tests"]
    results = report.get("results", [])
    if isinstance(results, dict):
        return results
    return {item.get("id", item.get("name")): item for item in results}


def counts(report: dict) -> dict:
    return {
        state: sum(item.get("status") == state for item in report_tests(report).values())
        for state in ("passed", "failed", "rate_limited", "skipped")
    }


def _read_json(path, snapshot):
    if snapshot is None:
        return json.loads(path.read_text(encoding="utf-8"))
    identity = path.resolve()
    if identity not in snapshot:
        snapshot[identity] = path.read_text(encoding="utf-8")
    # Separate mutable objects, identical source bytes for both languages.
    return json.loads(snapshot[identity])


def expected_outputs(language="zh", *, _snapshot=None) -> dict[Path, str]:
    if language not in {"zh", "en"}:
        raise ValueError("Unknown page language")
    english = language == "en"
    catalog = _read_json(CATALOG, _snapshot)
    lines = [
        "# Historical workflow verification status", "",
        "[中文](../../docs/验证状态.md) | English", "",
        "> Generated by `python skills/model-manual/scripts/sync_verification.py` from model cards and sanitized reports. Regenerate after updating evidence; this command sends no API requests.", "",
        "The vendor capability summary describes only each project's default model. Environments, parameters, scope, and outcomes come from the linked reports. "
        "Officially documented support and an observed execution result are recorded separately. [Evidence policy](evidence-policy.md)", "",
        "This page summarizes the historical shared workflow checks, not the current execution state of every example. "
        "See [example execution status](example-status.md) for current source hashes and real HTTP metadata. The two evidence layers cannot substitute for one another. Reports omit test timestamps and durations.", "",
        "| Model | Scope | Passed | Failed | Rate-limited | Skipped | SDK | Original report |",
        "|---|---|---:|---:|---:|---:|---|---|",
    ] if english else [
        "# 历史统一流程验证状态",
        "",
        "中文 | [English](../en/docs/verification-status.md)", "",
        "> 本页由 `python skills/model-manual/scripts/sync_verification.py` 从型号卡片与脱敏报告生成；请更新报告后重新生成。本命令不发送 API 请求。",
        "",
        "厂商能力摘要只指项目默认型号；具体环境、参数、测试范围和结果以每行的报告为准。官方文档声明与一次运行结果分别记录。[来源规则](来源与核验规则.md)",
        "",
        "本页只汇总旧统一验证器的能力检查，不代表当前每个示例文件的执行状态。逐文件源码哈希与真实 HTTP 元数据见[示例实测状态](示例实测状态.md)；两层报告不能互相替代。报告不记录测试日期时间与耗时。",
        "",
        "| 型号 | 验证范围 | 通过 | 失败 | 限流 | 跳过 | SDK | 原始报告 |",
        "|---|---|---:|---:|---:|---:|---|---|",
    ]
    for vendor, cfg in catalog["vendors"].items():
        card_path = REFERENCES / "models" / f'{cfg["default_model"]}.json'
        card = _read_json(card_path, _snapshot)
        if card["vendor"] != vendor or card["model_id"] != cfg["default_model"]:
            raise ValueError(f"型号归属不一致：{cfg['default_model']}")
        cfg["model_card"] = f'models/{card_path.name}'
        reference = card.get("verification")
        report = None
        report_path = None
        if reference is None:
            # 已有官方资料但尚未实测是正式状态，不能猜测报告名或继承厂商旧结果。
            if card.get("verification_scope", "not_run") != "not_run":
                raise ValueError(f"缺少报告时验证范围必须是 not_run：{card['model_id']}")
            cfg["verification"] = None
            cfg["verification_scope"] = "not_run"
        else:
            if not isinstance(reference, str) or not reference.strip():
                raise ValueError(f"报告引用须为非空路径或 null：{card['model_id']}")
            report_path = (card_path.parent / reference).resolve()
            if not report_path.is_file():
                raise ValueError(f"已登记的报告文件不存在：{card['model_id']}")
            report = _read_json(report_path, _snapshot)
            if report["model_id"] != card["model_id"]:
                raise ValueError(f"型号与报告不一致：{card['model_id']}")
            cfg["verification"] = report_path.relative_to(ROOT.resolve()).as_posix()
            cfg["verification_scope"] = "strict_workflow" if report.get("schema_version", 1) >= 2 else "legacy_smoke"
        observations = report_tests(report) if report is not None else {}
        capability_states = {}
        for name, capability in card["capabilities"].items():
            if name in TEST_IDS:
                status = observations.get(TEST_IDS[name], {}).get("status")
                if status == "passed":
                    capability_states[name] = "verified"
                elif capability["status"] in {"not_documented_for_this_model", "unknown", "unsupported"}:
                    capability_states[name] = "unknown"
                else:
                    capability_states[name] = "documented"
            else:
                capability_states[name] = "unknown" if capability["status"] in {"not_documented_for_this_model", "unknown", "unsupported"} else "documented"
        if "thinking" in card["capabilities"]:
            off_body = card.get("generation", {}).get("thinking", {}).get("off", {}).get("value")
            capability_states["thinking_off"] = (
                "verified" if observations.get("thinking_disabled", {}).get("status") == "passed"
                else "documented" if off_body is not None else "unknown"
            )
        cfg["capabilities"] = capability_states
        manual_link = f'../../models/{vendor}/{card["model_id"]}/README.en.md' if english else f'../models/{vendor}/{card["model_id"]}/README.md'
        if report is None:
            if english:
                lines.append(f'| [{card["model_id"]}]({manual_link}) | Workflow not run | — | — | — | — | — | No report registered |')
            else:
                lines.append(f'| [{card["model_id"]}]({manual_link}) | 统一验证器未运行 | — | — | — | — | — | 报告空缺 |')
            continue
        result_counts = counts(report)
        report_link = ("../../" if english else "../") + report_path.relative_to(ROOT.resolve()).as_posix()
        scope = ("Strict workflow" if cfg["verification_scope"] == "strict_workflow" else "Legacy smoke check") if english else ("严格流程验证" if cfg["verification_scope"] == "strict_workflow" else "历史基础验证")
        unrecorded = "Not recorded" if english else "未记录"
        sdk = report.get("runtime", {}).get("openai", unrecorded)
        lines.append(
            f'| [{card["model_id"]}]({manual_link}) | {scope} | '
            f'{result_counts["passed"]} | {result_counts["failed"]} | {result_counts["rate_limited"]} | '
            f'{result_counts["skipped"]} | {sdk} | [JSON]({report_link}) |'
        )
    lines.extend([
        "", "## Interpretation", "",
        "- Workflow not run: the model card registers no report for this workflow. Counts and SDK are shown as —. This does not exclude file-level tests and does not establish that a capability is unsupported; check the example execution page.",
        "- Legacy smoke check: evidence is limited to the conditions checked at the time. Old reports do not establish complete finish-reason checks, a tool-result round trip, or image-content recognition; those conclusions are not retroactively added.",
        "- Strict workflow: the script checks the finish reason and text. Tool checks validate arguments, return results, and require a final answer; image checks assert the test image's content. The report still determines which checks actually ran.",
        "- Rate-limited or skipped: no capability-validation conclusion was obtained. HTTP 429 does not establish authentication failure or unsupported functionality.",
        "- SDK version: historical reports retain their original environment. Reproducible current installation uses [requirements-lock.txt](../../requirements-lock.txt).", "",
        "Installation, reruns, report storage, and exit codes: [verification and reproduction](verification.md). "
        "Current file-level evidence: [example execution status](example-status.md).", "",
    ] if english else [
        "",
        "## 如何解读",
        "",
        "- 统一验证器未运行：型号卡片没有登记此类报告；计数与 SDK 显示为 —。这不代表没有逐文件实测，也不等于能力不支持；文件级记录请看示例实测状态页。",
        "- 历史基础验证：只证明脚本当时检查过的条件；旧报告没有记录完整结束原因、工具回传闭环或图片内容识别，不自动补写这些结论。",
        "- 严格流程验证：脚本检查结束原因和正文；工具项包含参数验证、结果回传和最终答复；图片项包含测试图内容断言。具体选中了哪些测试仍以报告为准。",
        "- 限流与跳过：没有获得能力验证结论；HTTP 429 不等于鉴权失败或模型不支持。",
        "- SDK 版本：历史报告保留原环境；本项目当前可复现安装使用 [requirements-lock.txt](../requirements-lock.txt)。",
        "",
        "安装、复测、报告保存与退出码见[验证与复现](验证与复现.md)。",
        "",
    ])
    return {
        CATALOG: json.dumps(catalog, ensure_ascii=False, indent=2) + "\n",
        (ROOT / "en/docs/verification-status.md" if english else STATUS_PAGE): "\n".join(lines),
    }


def all_expected_outputs() -> dict[Path, str]:
    snapshot = {}
    chinese, english = expected_outputs(_snapshot=snapshot), expected_outputs(language="en", _snapshot=snapshot)
    if chinese[CATALOG] != english[CATALOG]:
        raise ValueError("Canonical evidence changed during bilingual generation")
    return {**chinese, **english}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="只检查生成内容是否同步")
    args = parser.parse_args(argv)
    changed = []
    for path, expected in all_expected_outputs().items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current == expected:
            continue
        changed.append(path)
        if not args.check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8")
    if args.check and changed:
        print("需要重新生成：" + ", ".join(str(p.relative_to(ROOT)) for p in changed))
        return 1
    print("验证摘要已同步。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
